def register_i18n(app):
    @app.before_request
    def load_language():
        language = session.get("language", "en")
        if language not in SUPPORTED_LANGUAGES:
            language = "en"
        g.language = language

    @app.context_processor
    def inject_i18n():
        language = g.get("language", "en")
        return {
            "_": translate,
            "tr": translate_value,
            "rt": translate_report_text,
            "setting_label": setting_label,
            "setting_description": setting_description,
            "current_language": language,
            "supported_languages": SUPPORTED_LANGUAGES,
            "ui_text": TRANSLATIONS.get(language, {}),
        }

    @app.get("/language/<language>")
    def set_language(language):
        if language in SUPPORTED_LANGUAGES:
            session["language"] = language
        return redirect(request.referrer or url_for("dashboard"))


def translate(key, default=None):
    language = g.get("language", "en")
    if language == "en":
        return default or _fallback_text(key)
    return TRANSLATIONS.get(language, {}).get(key, default or _fallback_text(key))


def translate_value(value, default=None):
    if value is None:
        return default or "--"
    if g.get("language", "en") == "en":
        return default or _humanize(value)
    normalized = str(value).strip().lower().replace(" ", "_")
    return VALUE_TEXT_VI.get(normalized, default or _humanize(value))


def setting_label(key, default):
    if g.get("language", "en") == "en":
        return default
    return SETTING_TEXT_VI.get(key, (default, ""))[0]


def setting_description(key, default):
    if g.get("language", "en") == "en":
        return default
    return SETTING_TEXT_VI.get(key, ("", default))[1]


